function validateStep1() {
  let ok = true;
  // Validate declaration type
  const declType = document.querySelector('[name="declarationType"]:checked');
  if(!declType) { alert('يجب اختيار نوع التصريح'); return false; }

  const userType = document.getElementById('userType').value;
  if(userType === 'citizen') {
    // NIN: 18 digits, first digit 1 or 2
    const nin = document.getElementById('nin');
    const ninVal = (nin.value || '').trim();
    const ninValid = /^[12]\d{17}$/.test(ninVal);
    setError(nin.closest('.field'), !ninValid);
    if(!ninValid) ok = false;
  } else if(userType === 'resident') {
    // Foreign resident: residence card number required (non-empty)
    const passportEl = document.getElementById('passportNum');
    if(passportEl) {
      const pVal = (passportEl.value || '').trim();
      setError(passportEl.closest('.field'), !pVal);
      if(!pVal) ok = false;
    }
  } else if(userType === 'tourist') {
    // Tourist: passport number required (non-empty, at least 6 chars)
    const passportEl = document.getElementById('passportNum');
    if(passportEl) {
      const pVal = (passportEl.value || '').trim();
      const pValid = pVal.length >= 6;
      setError(passportEl.closest('.field'), !pValid);
      if(!pValid) ok = false;
    }
  } else if(userType === 'entity') {
    // Legal entity: entity name required
    const entityEl = document.getElementById('entityName');
    if(entityEl) {
      const eVal = (entityEl.value || '').trim();
      setError(entityEl.closest('.field'), !eVal);
      if(!eVal) ok = false;
    }
  }
  // Validate gender
  const genderField = document.getElementById('gender-field');
  const userTypeForGender = document.getElementById('userType').value;
  if(userTypeForGender !== 'entity') {
    const selGender = getSelectedGender();
    if(!selGender) {
      const errEl = document.getElementById('gender-err');
      if(errEl) errEl.style.display = 'block';
      ok = false;
    }
  }

  // Address (required for all types)
  const addrEl = document.getElementById('addressResidence');
  if(addrEl) {
    if(!addrEl.value.trim()) { setError(addrEl.closest('.field'), true); ok=false; }
    else { setError(addrEl.closest('.field'), false); }
  }

  // For legal entities (entity), skip personal fields (name, birth date, birth place)
  const isForeignType = (userType === 'resident' || userType === 'tourist');
  if(userType === 'entity') {
    // For entity: only validate residence, address and entity phone
    ['wilayaResidence','communeResidence'].forEach(id => {
      const el = document.getElementById(id);
      if(!el) return;
      if(!el.value.trim()) { setError(el.closest('.field'), true); ok=false; }
      else { setError(el.closest('.field'), false); }
    });
    const entityPhone = document.getElementById('phone-entity');
    if(entityPhone && !entityPhone.value.trim()) { setError(entityPhone.closest('.field'), true); ok=false; }
    else if(entityPhone) { setError(entityPhone.closest('.field'), false); }
  } else if(isForeignType) {
    // For foreign: validate unified name field, birth date, birth place, residence, phone
    const foreignName = document.getElementById('foreignName');
    if(foreignName && !foreignName.value.trim()) { setError(foreignName.closest('.field'), true); ok=false; }
    else if(foreignName) { setError(foreignName.closest('.field'), false); }
    const birthApprox = document.getElementById('birthDateApprox')?.checked;
    const birthFields = birthApprox ? ['birthYear','birthPlace','wilayaResidence','communeResidence'] : ['birthDate','birthPlace','wilayaResidence','communeResidence'];
    birthFields.forEach(id => {
      const el = document.getElementById(id);
      if(!el) return;
      if(!el.value.trim()) { setError(el.closest('.field'), true); ok=false; }
      else { setError(el.closest('.field'), false); }
    });
    // validate phone
    const phoneEl = document.getElementById('phone');
    if(phoneEl && !phoneEl.value.trim()) { setError(document.getElementById('phone-field-wrapper'), true); ok=false; }
    else if(phoneEl) { setError(document.getElementById('phone-field-wrapper'), false); }
  } else {
    // Citizen: validate names (Arabic + Latin), father, mother, birth, residence, phone
    const birthApprox = document.getElementById('birthDateApprox')?.checked;
    const birthFields = birthApprox
      ? ['lastName','firstName','birthYear','birthPlace','wilayaResidence','communeResidence']
      : ['lastName','firstName','birthDate','birthPlace','wilayaResidence','communeResidence'];
    birthFields.forEach(id => {
      const el = document.getElementById(id);
      if(!el) return;
      if(!el.value.trim()) { setError(el.closest('.field'), true); ok=false; }
      else { setError(el.closest('.field'), false); }
    });
    // Latin names (shown for citizen only)
    ['lastNameLat','firstNameLat'].forEach(id => {
      const el = document.getElementById(id);
      const field = document.getElementById(id + '-field');
      if(!el || !field || field.style.display === 'none') return;
      if(!el.value.trim()) { setError(el.closest('.field'), true); ok=false; }
      else { setError(el.closest('.field'), false); }
    });
    // Father and mother names (shown for non-entity)
    ['fatherName','motherName'].forEach(id => {
      const el = document.getElementById(id);
      const field = document.getElementById(id + '-field');
      if(!el || !field || field.style.display === 'none') return;
      if(!el.value.trim()) { setError(el.closest('.field'), true); ok=false; }
      else { setError(el.closest('.field'), false); }
    });
    // validate phone
    const phoneEl = document.getElementById('phone');
    if(phoneEl && !phoneEl.value.trim()) { setError(document.getElementById('phone-field-wrapper'), true); ok=false; }
    else if(phoneEl) { setError(document.getElementById('phone-field-wrapper'), false); }
  }
  return ok;
}

